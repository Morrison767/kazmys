/**
 * Пользователи и роли. В проде авторизация — по ИИН через HR API + SMS-код
 * (двухфакторная, без Active Directory, аналогично приложению SEN).
 * В прототипе роль переключается вручную в шапке.
 */

export type UserRole =
  | "customer" /** Заказчик — ответственный на участке / в цехе */
  | "approver" /** Согласующий — начальник цеха / участка */
  | "admin" /** Администратор ТД — специалист Торгового Дома */
  | "manager"; /** Руководитель — руководство ТД / Группы */

export interface User {
  id: string;
  /** ФИО полностью. */
  fullName: string;
  /** Инициалы для аватара в шапке. */
  initials: string;
  role: UserRole;
  position: string;
  /** ИИН — идентификатор в HR-системе (в прототипе маскированный). */
  iin?: string;
  phone?: string;
  email?: string;
  /** Привязанный цех — для Заказчика и Согласующего. */
  workshopId?: string;
  /** Предприятие — для Заказчика, Согласующего и локальных руководителей. */
  enterpriseId?: string;
  /** Администратор ТД и Руководитель работают в разрезе всех регионов. */
  regionIds?: string[];
  /**
   * Подотчётные цеха — для Согласующего: заказы этих цехов попадают
   * к нему в очередь согласований.
   */
  supervisedWorkshopIds?: string[];
  /**
   * Порог доп. согласования, ₸: заказы выше порога цеха уходят также
   * бюджетному контролёру / руководителю подразделения.
   */
  approvalCeiling?: number;
}

/** Метаданные роли для UI (название, описание, стартовый маршрут). */
export interface RoleMeta {
  role: UserRole;
  label: string;
  description: string;
  homePath: string;
}
