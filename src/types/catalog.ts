/**
 * Каталог: категории, номенклатура, поставщики.
 * Модель закупа — «один поставщик на категорию»: тендер через СЭТ проводится
 * один раз на период, заключается рамочный договор, каталог формируется
 * из номенклатуры выбранного поставщика.
 */

/** Этап разворачивания категории (см. «Категории и этапность»). */
export type RolloutStage = "pilot" | "stage2" | "stage3" | "stage4" | "next";

/**
 * Категория каталога. Иерархия через parentId — заложена под будущее
 * расширение (электротехника, КИП, стройматериалы, кабельная продукция).
 */
export interface Category {
  id: string;
  name: string;
  /** null — категория верхнего уровня. */
  parentId: string | null;
  /** Этап, на котором категория подключается к маркетплейсу. */
  stage: RolloutStage;
  /** Категория доступна для заказа (тендер проведён, договор действует). */
  isActive: boolean;
  /** Иконка lucide для навигации по каталогу. */
  icon?: string;
  description?: string;
}

/** Статус рамочного договора с поставщиком. */
export type ContractStatus =
  | "active" /** Действует */
  | "expiring" /** Истекает (менее 60 дней) */
  | "expired" /** Истёк */
  | "suspended" /** Приостановлен */
  | "draft"; /** Проект (тендер проведён, договор не подписан) */

/**
 * Поставщик. Одна категория на поставщика — прямое следствие модели
 * «один поставщик на категорию».
 */
export interface Supplier {
  id: string;
  name: string;
  bin: string;
  /** Категория, которую обслуживает поставщик (одна). */
  categoryId: string;
  /** Номер рамочного договора. */
  contractNumber: string;
  /** Дата заключения рамочного договора (ISO). */
  contractDateFrom: string;
  /** Срок действия рамочного договора (ISO). */
  contractDateTo: string;
  contractStatus: ContractStatus;
  /** Номер лота / тендера в СЭТ, по итогам которого выбран поставщик. */
  tenderNumber?: string;
  /** Покрытие номенклатуры категории, % — критерий выбора на тендере. */
  nomenclatureCoverage?: number;
  /**
   * Нормативный срок поставки по рамочному договору, дней:
   * от согласования заявки до приёмки товара. Используется в аналитике
   * сроков поставки как база для расчёта отклонения.
   */
  normativeDeliveryDays?: number;
  contactPerson?: string;
  contactPhone?: string;
  contactEmail?: string;
  /** Количество позиций поставщика в каталоге. */
  productCount?: number;
}

/** Единица измерения номенклатуры. */
export type UnitOfMeasure =
  | "шт"
  | "упак"
  | "компл"
  | "кг"
  | "л"
  | "м"
  | "рул"
  | "пач"
  | "пара"
  | "набор";

/** Остаток позиции на конкретном РЕСХ. */
export interface StockBalance {
  warehouseId: string;
  regionId: string;
  /** Свободный остаток. Источник в проде — OData D365 F&O, обновление 15 мин. */
  quantity: number;
  /** Зарезервировано под уже согласованные заказы. */
  reserved?: number;
  /** Момент последней синхронизации остатка (ISO). */
  updatedAt?: string;
}

/** Товарная позиция каталога. */
export interface Product {
  id: string;
  name: string;
  /** Артикул поставщика. */
  sku: string;
  /** Код номенклатуры в D365 F&O. */
  erpItemId?: string;
  categoryId: string;
  supplierId: string;
  unit: UnitOfMeasure;
  /** Цена по рамочному договору, ₸ без НДС. */
  price: number;
  /** Ставка НДС, % (обычно 12). */
  vatRate: number;
  /** Остатки по РЕСХ регионов. */
  stock: StockBalance[];
  /** Основной РЕСХ хранения позиции. */
  primaryWarehouseId: string;
  /** Регион основного РЕСХ — для быстрой фильтрации в каталоге. */
  primaryRegionId: string;
  imageUrl?: string;
  description?: string;
  /** Нормативный срок службы, дней — база для аналитики ходимости. */
  serviceLifeDays?: number;
  /**
   * Внешний источник позиции — маркетплейс, из которого подтянута карточка
   * («Garwin», «Lamed», «TSSP»). Визуальный атрибут: договор и поставщик
   * категории от него не зависят (модель «один поставщик на категорию»
   * остаётся в силе). Пусто — позиция из основного каталога поставщика.
   */
  externalSource?: string;
  /** Позиция скрыта администратором ТД (не показывается в каталоге). */
  isArchived?: boolean;
}
