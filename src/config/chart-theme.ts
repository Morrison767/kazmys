/**
 * Палитра и параметры графиков аналитики.
 *
 * Категориальные цвета назначаются в фиксированном порядке (по категории
 * закупа), а не по месту в рейтинге — фильтр не должен перекрашивать серии.
 * Набор проверен на белой поверхности: диапазон светлоты, минимум насыщенности,
 * различимость соседних пар при дальтонизме и контраст к фону — все проверки
 * пройдены. Пара «тиловый ↔ охра» слабо различима при тританопии, поэтому
 * идентичность серий дублируется легендой и подписями, а не только цветом.
 */
export const CHART_COLORS = [
  "#2474F5", // бренд-синий (--primary)
  "#0D9488", // тиловый
  "#C2610A", // охра
  "#7C3AED", // фиолетовый
] as const;

/** Цвет серии по индексу категории — стабилен между рендерами и фильтрами. */
export function chartColorAt(index: number): string {
  return CHART_COLORS[index % CHART_COLORS.length];
}

